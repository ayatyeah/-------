/**
 * Сброс пароля админки — на случай, когда пароль забыли.
 *
 * Запуск на сервере:
 *     docker compose exec web node server/reset-password.js
 * Локально:
 *     npm run reset-password
 *
 * ─── Зачем отдельная команда ────────────────────────────────────────────
 * Пароль, заданный через админку, хранится в виде scrypt-хэша: восстановить
 * из него исходный пароль нельзя — в этом весь смысл. Значит, нужен
 * законный способ сброса для того, у кого есть доступ к самому серверу.
 *
 * Сознательно НЕ сделано «секретной ссылкой» или переменной-отмычкой в
 * .env: любой такой обходной путь доступен и тому, кто до сайта доберётся
 * снаружи. Здесь же требуется доступ к машине по SSH — а у кого он есть,
 * тот и так хозяин положения.
 *
 * После сброса вход снова работает по ADMIN_PASSWORD из .env, и первым
 * делом стоит задать свой пароль в админке («Настройки» → «Пароль»).
 */
import * as store from './store.js'

store.load()

if (!store.auth.hasPassword()) {
  console.log('Свой пароль и не был задан — вход работает по ADMIN_PASSWORD из .env.')
  process.exit(0)
}

store.auth.clear()
store.flush()

console.log('✓ Пароль, заданный через админку, сброшен.')
console.log('  Вход снова работает по ADMIN_PASSWORD из .env.')
console.log('  Все открытые сессии админки при этом стали недействительными.')
console.log('\n  Дальше: войдите и сразу задайте свой пароль в «Настройки» → «Пароль админки».')
