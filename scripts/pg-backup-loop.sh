#!/bin/sh
# ============================================================================
#  Резервное копирование PostgreSQL. Крутится в контейнере db-backup.
#
#  Копия базы дополняет копию store.json, а не заменяет её:
#    • store.json — то, из чего сайт поднимается мгновенно и без базы;
#    • дамп — то, из чего восстанавливаются таблицы и индексы, и что можно
#      залить в другую базу (перенос на новый сервер, выгрузка в 1С).
#
#  Формат custom (-Fc): сжат и позволяет восстанавливать выборочно, по одной
#  таблице. Обычный текстовый .sql такого не умеет.
# ============================================================================
set -eu

BACKUP_DIR="${BACKUP_DIR:-/backups}"
KEEP_DAYS="${BACKUP_KEEP_DAYS:-14}"
EVERY="${BACKUP_EVERY:-86400}"

mkdir -p "$BACKUP_DIR"

make_backup() {
  stamp=$(date +%Y-%m-%d_%H%M%S)
  file="$BACKUP_DIR/pg-${PGDATABASE}-${stamp}.dump"

  # Пишем во временный файл и переименовываем только после успеха. Иначе
  # оборванный на середине дамп лежал бы в папке с правильным именем и
  # выглядел как годная копия — до того дня, когда его попробуют накатить.
  if pg_dump -Fc --no-owner --no-acl -f "${file}.tmp" 2>/tmp/pgdump.err; then
    mv "${file}.tmp" "$file"
    size=$(du -h "$file" | cut -f1)
    echo "$(date '+%Y-%m-%d %H:%M:%S')  ✓ копия базы: $(basename "$file") ($size)"
  else
    rm -f "${file}.tmp"
    echo "$(date '+%Y-%m-%d %H:%M:%S')  ✗ дамп не удался: $(tail -2 /tmp/pgdump.err | tr '\n' ' ')"
    return 1
  fi

  # Старое удаляем. Без этого папка бэкапов сама заполняет диск, и сервер
  # встаёт по причине, которую заводили ради надёжности.
  find "$BACKUP_DIR" -name "pg-*.dump" -type f -mtime "+$KEEP_DAYS" -delete 2>/dev/null || true
}

echo "Резервное копирование базы: раз в ${EVERY} с, хранение ${KEEP_DAYS} дн., папка ${BACKUP_DIR}"

# Первая копия — сразу, не через сутки. Иначе сервер, перезагруженный
# накануне ночного запуска, остаётся без копии вовсе.
make_backup || true

while true; do
  sleep "$EVERY"
  make_backup || true
done
