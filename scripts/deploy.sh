#!/usr/bin/env bash
# ============================================================================
#  Обновление сайта на сервере.
#
#      cd /opt/shm-agro && bash scripts/deploy.sh
#
#  Что делает: забирает изменения из git, собирает образ, поднимает
#  контейнеры, ждёт, пока сайт ответит, и — если не ответил — возвращает
#  предыдущую версию.
#
#  ─── Зачем отдельный скрипт вместо `docker compose up -d --build` ───────
#  Обычная команда сообщает об успехе, как только контейнер запущен. Но
#  «запущен» и «работает» — разные вещи: процесс может подняться и тут же
#  упасть на битой переменной окружения. Тогда сайт лежит, а деплой считает,
#  что всё хорошо. Здесь успех — это ответ от /api/health, и не раньше.
#
#  Данные при обновлении не трогаются: они на отдельном томе (shm-data),
#  который не пересоздаётся вместе с образом.
# ============================================================================
set -euo pipefail

cd "$(dirname "$0")/.."

шаг() { printf '\n\033[1m→ %s\033[0m\n' "$1"; }
ошибка() { printf '\n\033[31m✗ %s\033[0m\n' "$1"; }
готово() { printf '\033[32m✓ %s\033[0m\n' "$1"; }

# ---------------------------------------------------------------------------
шаг "Проверки перед обновлением"
# ---------------------------------------------------------------------------
if [ ! -f .env ]; then
  ошибка "нет файла .env — сначала создайте его из .env.example"
  exit 1
fi

# Пустой пароль или стандартный «admin» на проде закрывает вход в админку
# (так задумано), но об этом лучше узнать до деплоя, а не после.
if grep -qE '^ADMIN_PASSWORD=\s*$|^ADMIN_PASSWORD=admin\s*$' .env; then
  ошибка "в .env не задан свой ADMIN_PASSWORD — вход в админку будет закрыт"
  exit 1
fi
if grep -qE '^JWT_SECRET=\s*$' .env; then
  echo "  ⚠ JWT_SECRET пуст: после каждого деплоя придётся входить в админку заново"
  echo "    Сгенерировать: openssl rand -hex 32"
fi
готово "настройки на месте"

# ---------------------------------------------------------------------------
шаг "Резервная копия перед обновлением"
# ---------------------------------------------------------------------------
# Обновление не должно трогать данные, но копия перед изменениями — дешёвая
# страховка: если что-то пойдёт не так, откатываться будет к чему.
if docker compose ps --status running --services 2>/dev/null | grep -q backup; then
  docker compose exec -T backup sh /scripts/backup.sh || echo "  ⚠ копия не сделана, продолжаю"
fi

# ---------------------------------------------------------------------------
шаг "Забираю изменения из репозитория"
# ---------------------------------------------------------------------------
ПРЕДЫДУЩИЙ=$(git rev-parse HEAD)
echo "  текущая версия: ${ПРЕДЫДУЩИЙ:0:8}"

git fetch --quiet origin
git reset --hard origin/main --quiet
НОВЫЙ=$(git rev-parse HEAD)

if [ "$ПРЕДЫДУЩИЙ" = "$НОВЫЙ" ]; then
  готово "изменений нет — версия уже последняя"
else
  echo "  новая версия:   ${НОВЫЙ:0:8}"
  git --no-pager log --oneline "$ПРЕДЫДУЩИЙ..$НОВЫЙ" | sed 's/^/    /'
fi

# ---------------------------------------------------------------------------
шаг "Сборка и запуск"
# ---------------------------------------------------------------------------
docker compose build web
docker compose up -d

# ---------------------------------------------------------------------------
шаг "Проверяю, что сайт отвечает"
# ---------------------------------------------------------------------------
# Ждём до 90 секунд: столько нужно на старт процесса и первую проверку
# здоровья. Проверяем изнутри сети compose, чтобы не зависеть от домена и
# сертификата.
ОТВЕТИЛ=нет
for i in $(seq 1 30); do
  if docker compose exec -T web node -e \
    "fetch('http://127.0.0.1:3001/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    ОТВЕТИЛ=да
    break
  fi
  sleep 3
done

if [ "$ОТВЕТИЛ" = "да" ]; then
  готово "сайт отвечает, обновление завершено"
  docker compose ps
  # Старые образы занимают место; на диске в 25 ГБ это ощутимо.
  docker image prune -f >/dev/null 2>&1 || true
  exit 0
fi

# ---------------------------------------------------------------------------
ошибка "сайт не отвечает — возвращаю предыдущую версию"
# ---------------------------------------------------------------------------
echo
echo "Последние строки лога:"
docker compose logs --tail 40 web | sed 's/^/    /'
echo

git reset --hard "$ПРЕДЫДУЩИЙ" --quiet
docker compose build web
docker compose up -d

echo
ошибка "откат выполнен на версию ${ПРЕДЫДУЩИЙ:0:8}"
echo "  Причина в логе выше. Данные и фотографии не пострадали — они на отдельном томе."
exit 1
