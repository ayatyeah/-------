#!/usr/bin/env bash
# ============================================================================
#  Укрепление VPS под сайт СХМ Агро.
#
#  Запуск от root на чистом Ubuntu 22.04/24.04:
#      sudo bash scripts/harden-vps.sh
#
#  Скрипт можно запускать повторно: каждый шаг проверяет, не сделан ли он
#  уже. Ничего не ломает и не удаляет.
#
#  ─── Зачем это отдельно от Docker ────────────────────────────────────────
#  Приложение защищено неплохо: строгий CSP, лимиты частоты, контейнер без
#  привилегий и с файловой системой только на чтение. Но всё это защищает
#  сайт, а не сервер. Практика такая: машину ломают не через форму заявки,
#  а через подбор пароля к SSH, забытый открытый порт или непропатченное
#  ядро. Ниже — ровно эти три вещи.
#
#  ВНИМАНИЕ про SSH: скрипт отключает вход по паролю. Перед запуском
#  убедитесь, что ключ уже добавлен и вход по нему работает — иначе
#  закроете себе доступ к серверу. Скрипт проверяет это сам и без ключей
#  отказывается трогать SSH.
# ============================================================================
set -euo pipefail

шаг() { printf '\n\033[1m→ %s\033[0m\n' "$1"; }
готово() { printf '  ✓ %s\n' "$1"; }
внимание() { printf '  ⚠ %s\n' "$1"; }

if [ "$(id -u)" -ne 0 ]; then
  echo "Запускать нужно от root: sudo bash $0"
  exit 1
fi

# ---------------------------------------------------------------------------
шаг "1. Обновление системы и автоматические обновления безопасности"
# ---------------------------------------------------------------------------
# Самая частая причина взлома сервера — незакрытая известная уязвимость, к
# которой давно вышло обновление. Раз машина без администратора, обновления
# безопасности должны ставиться сами.
export DEBIAN_FRONTEND=noninteractive
# needrestart без TTY пытается показать диалог и вешает установку намертво
export NEEDRESTART_MODE=a
export NEEDRESTART_SUSPEND=1

apt-get update -q
# --force-confold: не спрашивать про изменённые конфиги, оставлять текущие
apt-get -y -q \
  -o Dpkg::Options::="--force-confold" \
  -o Dpkg::Options::="--force-confdef" \
  upgrade
apt-get install -y -q unattended-upgrades ufw fail2ban curl

cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
EOF

# Перезагружаемся сами, если обновление того требует (обновление ядра).
# Ночью в 4 утра: сайт поднимется сам, так как контейнеры с restart-политикой.
sed -i 's|^//Unattended-Upgrade::Automatic-Reboot ".*";|Unattended-Upgrade::Automatic-Reboot "true";|' /etc/apt/apt.conf.d/50unattended-upgrades || true
sed -i 's|^//Unattended-Upgrade::Automatic-Reboot-Time ".*";|Unattended-Upgrade::Automatic-Reboot-Time "04:00";|' /etc/apt/apt.conf.d/50unattended-upgrades || true
готово "обновления безопасности ставятся автоматически"

# ---------------------------------------------------------------------------
шаг "2. Файрвол"
# ---------------------------------------------------------------------------
# Открыты ровно три порта. Всё остальное закрыто: у сервера не должно быть
# ни одной двери, о которой не знает владелец.
ufw --force reset >/dev/null
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow 22/tcp comment 'SSH' >/dev/null
ufw allow 80/tcp comment 'HTTP (перенаправление на HTTPS)' >/dev/null
ufw allow 443/tcp comment 'HTTPS' >/dev/null
ufw allow 443/udp comment 'HTTP/3' >/dev/null
ufw --force enable >/dev/null
готово "открыты только 22, 80, 443"

# Docker умеет проходить мимо ufw, публикуя порты прямо в iptables.
# Здесь это не мешает: наружу публикует порты только Caddy, и ровно те же
# 80/443. Но знать об этом полезно — если кто-то добавит `ports:` сервису
# web, порт станет доступен снаружи в обход файрвола.
внимание "Docker публикует порты в обход ufw — не добавляйте ports: сервису web"

# ---------------------------------------------------------------------------
шаг "3. Защита SSH от перебора паролей"
# ---------------------------------------------------------------------------
cat > /etc/fail2ban/jail.local <<'EOF'
[DEFAULT]
# Сколько держать в бане и за какое окно считать попытки.
bantime  = 1h
findtime = 10m
maxretry = 5
# Повторным нарушителям срок растёт.
bantime.increment = true
bantime.factor = 2
bantime.maxtime = 48h

[sshd]
enabled = true
port    = 22
EOF

systemctl enable fail2ban >/dev/null 2>&1 || true
systemctl restart fail2ban
готово "fail2ban включён: 5 неудачных попыток — бан на час"

# ---------------------------------------------------------------------------
шаг "4. Вход по SSH только по ключу"
# ---------------------------------------------------------------------------
# Отключаем вход по паролю — но только если ключи уже настроены. Иначе
# скрипт запер бы владельца снаружи, и восстанавливать доступ пришлось бы
# через консоль хостера.
KEYS=0
for f in /root/.ssh/authorized_keys /home/*/.ssh/authorized_keys; do
  [ -s "$f" ] && KEYS=$((KEYS + 1))
done

if [ "$KEYS" -gt 0 ]; then
  cat > /etc/ssh/sshd_config.d/99-hardening.conf <<'EOF'
# Вход только по ключу: пароль к SSH подбирают круглосуточно, ключ — нет.
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
# Пустые пароли и .rhosts — наследие, которое сегодня только мешает.
PermitEmptyPasswords no
# Меньше времени на попытку входа и меньше одновременных попыток.
LoginGraceTime 30
MaxAuthTries 3
MaxSessions 5
# Проброс X11 на сервере без графики не нужен и расширяет поверхность атаки.
X11Forwarding no
EOF
  if sshd -t 2>/dev/null; then
    systemctl reload ssh 2>/dev/null || systemctl reload sshd
    готово "вход по паролю отключён (найдено файлов с ключами: $KEYS)"
  else
    rm -f /etc/ssh/sshd_config.d/99-hardening.conf
    внимание "конфигурация SSH не прошла проверку — оставил как было"
  fi
else
  внимание "SSH-ключей не найдено — вход по паролю НЕ отключён"
  внимание "добавьте ключ (ssh-copy-id) и запустите скрипт повторно"
fi

# ---------------------------------------------------------------------------
шаг "5. Файл подкачки"
# ---------------------------------------------------------------------------
# На VPS с 1–2 ГБ сборка образа и пиковая нагрузка упираются в память, и
# ядро убивает процессы — чаще всего не тот, который виноват. Подкачка
# превращает падение в замедление.
if ! swapon --show | grep -q .; then
  MEM_MB=$(free -m | awk '/^Mem:/{print $2}')
  SWAP_SIZE=2G
  [ "$MEM_MB" -ge 4000 ] && SWAP_SIZE=1G
  fallocate -l "$SWAP_SIZE" /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=2048
  chmod 600 /swapfile
  mkswap /swapfile >/dev/null
  swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  # Подкачку используем неохотно: она медленная, нужна как страховка.
  sysctl -w vm.swappiness=10 >/dev/null
  grep -q 'vm.swappiness' /etc/sysctl.conf || echo 'vm.swappiness=10' >> /etc/sysctl.conf
  готово "файл подкачки $SWAP_SIZE создан"
else
  готово "подкачка уже настроена"
fi

# ---------------------------------------------------------------------------
шаг "6. Ограничение логов Docker"
# ---------------------------------------------------------------------------
# Логи без ротации — самая частая причина «сайт лёг сам по себе» на
# маленьком VPS: диск заполняется, приложению некуда писать данные, приём
# заявок останавливается. В compose ротация задана для наших сервисов, но
# для всех остальных контейнеров её задаёт демон.
if [ ! -f /etc/docker/daemon.json ]; then
  mkdir -p /etc/docker
  cat > /etc/docker/daemon.json <<'EOF'
{
  "log-driver": "json-file",
  "log-opts": { "max-size": "10m", "max-file": "3" },
  "live-restore": true
}
EOF
  systemctl restart docker 2>/dev/null || true
  готово "ротация логов Docker настроена"
else
  внимание "/etc/docker/daemon.json уже есть — проверьте вручную наличие log-opts"
fi

# ---------------------------------------------------------------------------
шаг "7. Права на файл с секретами"
# ---------------------------------------------------------------------------
# В .env лежат пароль администратора, секрет подписи сессий и ключи ИИ.
# Читать его должен только владелец.
for env_file in /opt/shm-agro/.env /root/shm-agro/.env ./.env; do
  if [ -f "$env_file" ]; then
    chmod 600 "$env_file"
    готово "права 600 на $env_file"
  fi
done

# ---------------------------------------------------------------------------
шаг "Готово"
# ---------------------------------------------------------------------------
cat <<'EOF'

  Что сделано:
    • обновления безопасности ставятся сами, при смене ядра — перезагрузка в 4:00
    • открыты только порты 22, 80, 443
    • fail2ban банит за перебор пароля к SSH
    • вход по SSH только по ключу (если ключи были найдены)
    • создан файл подкачки
    • логи Docker ротируются

  Что скрипт сделать не может — это к владельцу:
    • проверить, что резервные копии реально уносятся с этого сервера
      (копия рядом с сайтом не спасает от потери самого сервера);
    • завести отдельного пользователя вместо работы под root;
    • включить у хостера снимки диска, если они есть.

EOF
