#!/usr/bin/env bash
# ============================================================================
#  Сторож: поднимает сайт, если он перестал отвечать.
#
#  Ставится в cron на самом сервере (не в контейнер!):
#      */5 * * * * /opt/shm-agro/scripts/watchdog.sh >> /var/log/shm-watchdog.log 2>&1
#
#  ─── Зачем он нужен, если есть restart: unless-stopped ──────────────────
#  Политика перезапуска Docker срабатывает, когда процесс ЗАВЕРШИЛСЯ. Но
#  бывает состояние хуже: процесс жив, а сайт не отвечает — заклинило на
#  бесконечном цикле, кончились файловые дескрипторы, зависла файловая
#  система тома. Docker в этом случае не делает ничего: с его точки зрения
#  контейнер работает. Проверка здоровья (healthcheck) такое состояние
#  видит и помечает контейнер unhealthy — но сама по себе тоже ничего не
#  предпринимает.
#
#  ─── Почему на хосте, а не контейнером autoheal ─────────────────────────
#  Готовые решения вроде willfarrell/autoheal требуют примонтировать внутрь
#  /var/run/docker.sock. Доступ к этому сокету равносилен правам root на
#  всей машине: через него можно запустить контейнер с примонтированным
#  корнем хоста. Ради перезапуска раз в полгода отдавать такой рычаг
#  дополнительному контейнеру — плохая сделка. Cron на хосте и так работает
#  от root, ничего нового он не открывает.
# ============================================================================
set -uo pipefail

ПРОЕКТ="${PROJECT_DIR:-/opt/shm-agro}"
cd "$ПРОЕКТ" || exit 0

лог() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"; }

СОСТОЯНИЕ=$(docker compose ps --format '{{.Name}} {{.State}} {{.Health}}' 2>/dev/null | grep -E '(^|-)web' || true)

if [ -z "$СОСТОЯНИЕ" ]; then
  лог "контейнер web не найден — поднимаю"
  docker compose up -d web
  exit 0
fi

case "$СОСТОЯНИЕ" in
  *unhealthy*)
    лог "web помечен unhealthy — перезапускаю"
    # Сохраняем хвост лога: после перезапуска причина исчезнет, а понять,
    # что произошло, потом захочется.
    docker compose logs --tail 60 web
    docker compose restart web
    лог "перезапуск выполнен"
    ;;
  *exited*|*restarting*)
    лог "web в состоянии «$СОСТОЯНИЕ» — поднимаю"
    docker compose logs --tail 60 web
    docker compose up -d web
    ;;
  *)
    # Здоров — молчим. Cron не должен писать в лог каждые пять минут.
    exit 0
    ;;
esac

# ─── Место на диске ────────────────────────────────────────────────────────
# Кончившийся диск останавливает запись store.json, то есть приём заявок.
# Предупредить лучше заранее.
ЗАНЯТО=$(df --output=pcent / | tail -1 | tr -d ' %')
if [ "${ЗАНЯТО:-0}" -ge 85 ]; then
  лог "ВНИМАНИЕ: диск занят на ${ЗАНЯТО}% — проверьте папку backups и docker system df"
fi
