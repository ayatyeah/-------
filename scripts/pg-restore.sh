#!/bin/sh
# ============================================================================
#  Восстановление PostgreSQL из дампа.
#
#      docker compose stop web
#      docker compose run --rm pg-restore
#      docker compose start web
#
#  Сайт останавливают обязательно: он держит данные в памяти, и полная
#  сверка зальёт в свежевосстановленную базу содержимое памяти — то есть
#  затрёт ровно то, что мы восстановили.
#
#  ─── КОГДА ЭТО НЕ НУЖНО ──────────────────────────────────────────────────
#  Если потерян только том с базой, а data/store.json на месте, руками
#  делать не надо ничего: сайт увидит пустую базу и перенесёт всё сам при
#  ближайшем запуске. Этот скрипт — для случая, когда потеряно и то и другое,
#  или когда нужно вернуть состояние на конкретную дату.
# ============================================================================
set -eu

BACKUP_DIR="${BACKUP_DIR:-/backups}"

echo "Доступные копии базы в $BACKUP_DIR:"
ls -1t "$BACKUP_DIR"/pg-*.dump 2>/dev/null | head -20 || {
  echo "  копий не найдено — восстанавливать нечего"
  exit 1
}

# Берём самую свежую, если не указали другую переменной RESTORE_FILE.
file="${RESTORE_FILE:-$(ls -1t "$BACKUP_DIR"/pg-*.dump 2>/dev/null | head -1)}"
[ -f "$file" ] || { echo "Файл не найден: $file"; exit 1; }

echo
echo "Восстанавливаю из: $file"
echo "База: $PGDATABASE на $PGHOST"
echo

# --clean --if-exists: сносим прежние таблицы перед заливкой. Без этого
# восстановление поверх существующих данных даёт конфликты ключей и
# половинчатый результат, который выглядит как успех.
#
# Ошибки не глушим, но и не считаем фатальными поштучно: pg_restore ругается
# на отсутствующие объекты при первом накате в пустую базу, и это нормально.
pg_restore --clean --if-exists --no-owner --no-acl -d "$PGDATABASE" "$file" 2>&1 | tail -20 || true

echo
echo "Проверка:"
psql -tAc "select 'моделей: '||count(*) from models" 2>/dev/null || true
psql -tAc "select 'заявок: '||count(*) from requests" 2>/dev/null || true
psql -tAc "select 'новостей: '||count(*) from news" 2>/dev/null || true

echo
echo "Готово. Теперь важное:"
echo "  1) Запустите сайт с DB_SOURCE=db, чтобы он поднялся ИЗ БАЗЫ,"
echo "     а не затёр её своим старым файлом:"
echo "        DB_SOURCE=db docker compose up -d web"
echo "  2) Убедитесь, что в админке данные на месте."
echo "  3) Верните DB_SOURCE=auto в .env и перезапустите:"
echo "        docker compose up -d web"
